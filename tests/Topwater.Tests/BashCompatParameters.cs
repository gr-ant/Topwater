    [InlineData("name=World; echo \"Hello, ${name}!\" 'Hello, ${name}!'", "Hello, World! Hello, ${name}!\n", 0, true)]
    [InlineData("echo \"${HOME}\" ~ ~/x \"~\" x~", "/home/agent /home/agent /home/agent/x ~ x~\n", 0, true)]
    [InlineData("v=~; echo $v; w=a:~/b; echo $w; export P=~/bin:~/x; echo $P", "/home/agent\na:/home/agent/b\n/home/agent/bin:/home/agent/x\n", 0, true)]
    [InlineData("echo ~root ~nosuchuser", "/root ~nosuchuser\n", 0, true)]
    [InlineData("x=\"${undefined:-}\"; echo \"[$x]\"", "[]\n", 0, true)]
    [InlineData("s=abc; echo ${s:1:100} \"${s:0:0}|\"", "bc |\n", 0, true)]
    [InlineData("s=hello; echo ${s%l*} ${s%%l*}", "hel he\n", 0, true)]
    [InlineData("s=\"/a/b/\"; echo \"${s%/}\" \"${s%%/}\"", "/a/b /a/b\n", 0, true)]
    [InlineData("x=\"a'b\\\"c\"; echo \"${x//\\'/Q}\" \"${x//\\\"/D}\"", "aQb\"c a'bDc\n", 0, true)]
    [InlineData("f=report.final.pdf; echo ${f%%.*} ${f#*.} ${f%.*} ${f##*.}", "report final.pdf report.final pdf\n", 0, true)]
    [InlineData("x=AbC; echo ${x~~} ${x~}", "aBc abC\n", 0, true)]
    [InlineData("num=007; echo $((10#$num)) $((num))", "7 7\n", 0, true)]
    [InlineData("s='a-b-c'; IFS=- read -r x y z <<< \"$s\"; echo \"$x|$y|$z\"", "a|b|c\n", 0, true)]
    [InlineData("str=hello; echo ${str:0:1}; echo ${str::2}", "h\nhe\n", 0, true)]
    [InlineData("v=x; echo ${v:+\"[$v]\"} ${nov:+\"[$nov]\"}end", "[x] end\n", 0, true)]
    [InlineData("echo \"${x:-$(echo sub)}\" \"${x:-`echo bt`}\"", "sub bt\n", 0, true)]
    [InlineData("echo \"${#}\" \"${#@}\" \"${#*}\"", "0 0 0\n", 0, true)]
    [InlineData("set -- a b c; echo \"${@:2}\" \"${*:1:2}\" \"${@: -1}\" \"${@:0:1}\"", "b c a b c bash\n", 0, true)]
    [InlineData("set -- a b c d; echo \"${!#}\" \"${@:$#}\"", "d d\n", 0, true)]
    [InlineData("v=abc; echo ${v//[a-b]/X} ${v//[!a]/Y}", "XXc aYY\n", 0, true)]
    [InlineData("s=aaa; echo ${s/a*/X} ${s//a/} ${s/a/}", "X aa\n", 0, true)]
    [InlineData("x=hello; echo \"${x:${#x}-2}\"", "lo\n", 0, true)]
    [InlineData("x=\"hello\"; echo \"${x^^l}\" \"${x,,L}\"", "heLLo hello\n", 0, true)]
    [InlineData("s=\"CamelCaseString\"; echo \"${s,}\" ", "camelCaseString\n", 0, true)]
    [InlineData("x=a; y=${x:-${z:-${w:-deep}}}; echo $y; unset x; y=${x:-${z:-${w:-deep}}}; echo $y", "a\ndeep\n", 0, true)]
    [InlineData("var=value; echo \"${var:+${var}_suffix}\"", "value_suffix\n", 0, true)]
    [InlineData("v='$HOME'; echo $v \"$v\"", "$HOME $HOME\n", 0, true)]
    [InlineData("s=\"a/b/c\"; echo ${s////-}", "a-b-c\n", 0, true)]
    [InlineData("s=\"x  y\"; echo \"${s// /}\"; echo ${s// /}", "xy\nxy\n", 0, true)]
    public Task MatchesBash(string script, string stdout, int exitCode, bool quiet) => BashCompat.Check(script, stdout, exitCode, quiet);
}
