using Topwater;

namespace Topwater.Tests;

/// <summary>Parameter expansion in its forms, with unset, empty and set values and under set -u. Generated from differential runs: each expected value is what bash 5.2.21 printed.</summary>
public class BashCompatParameters
{
    [Theory]
    [InlineData("unset x; echo \"[${x:-d}] [${x-d}] [${x:+a}] [${x+a}]\"", "[d] [d] [] []\n", 0, true)]
    [InlineData("x=; echo \"[${x:-d}] [${x-d}] [${x:+a}] [${x+a}]\"", "[d] [] [] [a]\n", 0, true)]
    [InlineData("x=v; echo \"[${x:-d}] [${x-d}] [${x:+a}] [${x+a}]\"", "[v] [v] [a] [a]\n", 0, true)]
    [InlineData("unset x; echo \"${x:=init}\"; echo \"$x\"; y=; echo \"${y=keep}|$y\"", "init\ninit\n|\n", 0, true)]
    [InlineData("unset x; : ${x:?missing value}; echo after", "", 127, false)]
    [InlineData("unset x; echo ${x?}; echo after", "", 127, false)]
    [InlineData("x=; (echo ${x:?}); echo \"status $?\"", "status 1\n", 0, false)]
    [InlineData("f() { local v=${1:?usage: f arg}; echo $v; }; f; echo \"rc=$?\"", "", 127, false)]
    [InlineData("set -u; unset x; echo \"${x:-ok}\" \"${x-ok2}\"; echo \"${x+set}\"", "ok ok2\n\n", 0, true)]
    [InlineData("set -u; echo \"$undefined_var\"; echo after", "", 127, false)]
    [InlineData("set -u; f() { echo \"${1:-none}\"; }; f", "none\n", 0, true)]
    [InlineData("set -u; f() { echo \"$1\"; }; f; echo rc=$?", "", 127, false)]
    [InlineData("x=hello; echo ${#x}; e=; echo ${#e}; echo ${#nosuch}", "5\n0\n0\n", 0, true)]
    [InlineData("p=/usr/local/lib/file.tar.gz; echo ${p%.*} ${p%%.*} ${p#*/} ${p##*/}", "/usr/local/lib/file.tar /usr/local/lib/file usr/local/lib/file.tar.gz file.tar.gz\n", 0, true)]
    [InlineData("p=file.tar.gz; echo \"${p%.gz}\" \"${p%.zip}\" \"${p#file}\"", "file.tar file.tar.gz .tar.gz\n", 0, true)]
    [InlineData("s=aaa-bbb-ccc; echo ${s/-/_} ${s//-/_} ${s/#aaa/X} ${s/%ccc/Y} ${s/#bbb/Z}", "aaa_bbb-ccc aaa_bbb_ccc X-bbb-ccc aaa-bbb-Y aaa-bbb-ccc\n", 0, true)]
    [InlineData("s='a b c'; echo \"${s// /}\" \"${s// /_}\"", "abc a_b_c\n", 0, true)]
    [InlineData("s=hello; echo \"${s/l/L}\" \"${s//l}\" \"${s/x/y}\"", "heLlo heo hello\n", 0, true)]
    [InlineData("s='path/to/file'; echo \"${s//\\//:}\"", "path:to:file\n", 0, true)]
    [InlineData("s='a.b.c'; echo \"${s//./\\\\}\"", "a\\b\\c\n", 0, true)]
    [InlineData("s=abc; echo \"${s/b/&x}\"", "abxc\n", 0, true)]
    [InlineData("s=abc; echo \"${s/b/\\&x}\"", "a&xc\n", 0, true)]
    [InlineData("s=hello; r='L'; echo \"${s//l/$r}\"", "heLLo\n", 0, true)]
    [InlineData("s='foo bar'; echo \"${s/[ao]/_}\" \"${s//[ao]/_}\" \"${s//?/x}\"", "f_o bar f__ b_r xxxxxxx\n", 0, true)]
    [InlineData("s='x*y'; echo \"${s/\\*/+}\" \"${s//[*]/-}\"", "x+y x-y\n", 0, true)]
    [InlineData("s='hello world'; echo \"${s/o*/!}\" \"${s/#h*o/X}\"", "hell! Xrld\n", 0, true)]
    [InlineData("s=Hello; echo ${s^} ${s^^} ${s,} ${s,,}; t=hello; echo ${t^}", "Hello HELLO hello hello\nHello\n", 0, true)]
    [InlineData("s='hello world'; echo \"${s^^[lo]}\"", "heLLO wOrLd\n", 0, true)]
    [InlineData("s=abcdef; echo ${s:2} ${s:2:2} ${s: -2} ${s:(-3):2} ${s:1:-1}", "cdef cd ef de bcde\n", 0, true)]
    [InlineData("s=abc; echo \"[${s:5}]\" \"[${s: -5}]\"", "[] []\n", 0, true)]
    [InlineData("s=abcdef; i=2; echo ${s:i:i+1} ${s:$i:1}", "cde c\n", 0, true)]
    [InlineData("s=abcdef; echo ${s:-2}", "abcdef\n", 0, true)]
    [InlineData("x=5; y=x; echo ${!y}", "5\n", 0, true)]
    [InlineData("x=\"it's\"; echo ${x@Q}", "'it'\\''s'\n", 0, true)]
    [InlineData("x=abc; echo ${x@Q}; x=; echo \"[${x@Q}]\"", "'abc'\n['']\n", 0, true)]
    [InlineData("a=1; b=${a:+\"set $a\"}; echo \"$b\"", "set 1\n", 0, true)]
    [InlineData("v=\"a b\"; echo ${v:-\"x y\"}; f() { echo $#; }; f ${v:-\"x y\"}; unset v; f ${v:-\"x y\"}", "a b\n2\n1\n", 0, true)]
    [InlineData("u=; f() { echo $#; }; f ${u:-a b c}; f \"${u:-a b c}\"", "3\n1\n", 0, true)]
    [InlineData("echo $'tab\\there' $'nl\\nx' $'q\\'q' $'\\x41é'", "tab\there nl\nx q'q Aé\n", 0, true)]
    [InlineData("echo $\"translated\"", "translated\n", 0, true)]
    [InlineData("x=abc; echo ${x:1:1}${x:0:1}", "ba\n", 0, true)]
    [InlineData("file=\"My Doc.TXT\"; ext=\"${file##*.}\"; echo \"${ext,,}\" \"${file%.*}\"", "txt My Doc\n", 0, true)]
    [InlineData("url=\"https://example.com:8080/path?q=1\"; host=${url#*://}; host=${host%%/*}; echo ${host%:*} ${host#*:}", "example.com 8080\n", 0, true)]
    [InlineData("x=10; echo \"${x:-$((x+1))}\" \"${y:-$((x+1))}\"", "10 11\n", 0, true)]
    [InlineData("str=\"key=value=more\"; echo \"${str%%=*}\" \"${str#*=}\"", "key value=more\n", 0, true)]
    [InlineData("v=\"  padded  \"; t=\"${v#\"${v%%[![:space:]]*}\"}\"; t=\"${t%\"${t##*[![:space:]]}\"}\"; echo \"[$t]\"", "[padded]\n", 0, true)]
    [InlineData("x='a*b'; y=aXXb; echo \"${y/$x/Z}\" \"${y/\"$x\"/Z}\"", "Z aXXb\n", 0, true)]
