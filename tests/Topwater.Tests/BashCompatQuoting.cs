using Topwater;

namespace Topwater.Tests;

/// <summary>Quoting, word splitting, IFS, globs (with shopt options) and brace expansion. Generated from differential runs: each expected value is what bash 5.2.21 printed.</summary>
public class BashCompatQuoting
{
    [Theory]
    [InlineData("echo \"$(echo \"inner \\\"quoted\\\" text\")\"", "inner \"quoted\" text\n", 0, true)]
    [InlineData("x=\"a b\"; echo \"$(echo \"$x\" | tr a-z A-Z)\"", "A B\n", 0, true)]
    [InlineData("echo \"a\\$b \\\\ \\` \\\"q\\\" \\n\"", "a$b \\ ` \"q\" \\n\n", 0, true)]
    [InlineData("echo 'single \\n $x \"dq\"'", "single \\n $x \"dq\"\n", 0, true)]
    [InlineData("cat <<EOF\nback\\\\slash \\$dollar \\`tick\\` \"q\" 'sq' \\n\nEOF", "back\\slash $dollar `tick` \"q\" 'sq' \\n\n", 0, true)]
    [InlineData("x=1; cat <<EOF\nval=$x $(echo cmd) $((1+2)) ${x:-d}\nEOF", "val=1 cmd 3 1\n", 0, true)]
    [InlineData("set -- \"a b\" c; for a in \"$@\"; do echo \"[$a]\"; done; for a in $*; do echo \"<$a>\"; done; for a in \"$*\"; do echo \"{$a}\"; done", "[a b]\n[c]\n<a>\n<b>\n<c>\n{a b c}\n", 0, true)]
    [InlineData("set -- a b c; IFS=,; echo \"$*\"; echo $*; echo \"$@\"; unset IFS", "a,b,c\na b c\na b c\n", 0, true)]
    [InlineData("set -- a b c; IFS=; echo \"$*\"; unset IFS", "abc\n", 0, true)]
    [InlineData("f() { echo $#; }; f \"\" \"\"; f ''; f; e=; f $e; f \"$e\"", "2\n1\n0\n0\n1\n", 0, true)]
    [InlineData("set -- x y; s=\"$@\"; echo \"$s\"; t=$@; echo \"$t\"", "x y\nx y\n", 0, true)]
    [InlineData("IFS=: read -r a b c <<< \"1:2:3:4\"; echo \"$a|$b|$c\"", "1|2|3:4\n", 0, true)]
    [InlineData("IFS=: read -r a b <<< \"1::3\"; echo \"$a|$b\"", "1|:3\n", 0, true)]
    [InlineData("x=\"a:b::c\"; IFS=:; set -- $x; echo $#; unset IFS", "4\n", 0, true)]
    [InlineData("x=\" a  b \"; IFS=' '; set -- $x; echo $#", "2\n", 0, true)]
    [InlineData("x=\"a,b,,c,\"; IFS=,; arr=($x); echo ${#arr[@]}; unset IFS", "4\n", 0, true)]
    [InlineData("x=\"a, b ,c\"; IFS=', '; arr=($x); echo ${#arr[@]} \"${arr[1]}\"", "3 b\n", 0, true)]
    [InlineData("touch a.txt b.txt; x='*.txt'; echo $x; echo \"$x\"", "a.txt b.txt\n*.txt\n", 0, true)]
    [InlineData("touch a.txt; set -f; echo *.txt; set +f; echo *.txt", "*.txt\na.txt\n", 0, true)]
    [InlineData("echo nomatch*.zzz; shopt -s nullglob; echo nomatch*.zzz end", "nomatch*.zzz\nend\n", 0, true)]
    [InlineData("touch .hidden vis; echo *; shopt -s dotglob; echo *", "vis\n.hidden vis\n", 0, true)]
    [InlineData("shopt -s extglob; [[ abc == @(abc|def) ]] && echo m1; [[ xyz == !(abc) ]] && echo m2; [[ aaa == +(a) ]] && echo m3; [[ \"\" == ?(x) ]] && echo m4; [[ b == *(a|b) ]] && echo m5", "m1\nm2\nm3\nm4\nm5\n", 0, true)]
    [InlineData("mkdir -p d/e; touch d/e/f.txt d/g.txt; shopt -s globstar; echo d/**/*.txt", "d/e/f.txt d/g.txt\n", 0, true)]
    [InlineData("shopt -s nocasematch; [[ ABC == abc ]] && echo ci; case XyZ in xyz) echo case-ci;; esac", "ci\ncase-ci\n", 0, true)]
    [InlineData("echo {a,b}{1,2}", "a1 a2 b1 b2\n", 0, true)]
    [InlineData("echo {1..10..3} {a..e} {01..10} {10..1..4} {e..a}", "1 4 7 10 a b c d e 01 02 03 04 05 06 07 08 09 10 10 6 2 e d c b a\n", 0, true)]
    [InlineData("echo pre{,.bak} file.{txt,md}", "pre pre.bak file.txt file.md\n", 0, true)]
    [InlineData("echo \"{a,b}\" '{a,b}' {a} {} {a,b", "{a,b} {a,b} {a} {} {a,b\n", 0, true)]
    [InlineData("x=1; echo {$x,2} {1..$x}", "1 2 {1..1}\n", 0, true)]
    [InlineData("echo a{b,c{d,e}}f", "abf acdf acef\n", 0, true)]
    [InlineData("echo {a..c}{1..2}", "a1 a2 b1 b2 c1 c2\n", 0, true)]
    [InlineData("echo \\{a,b\\} \\* \\? \"*\"", "{a,b} * ? *\n", 0, true)]
    [InlineData("echo {-1..2} {a..c..2}", "-1 0 1 2 a c\n", 0, true)]
    [InlineData("echo x{1..3}y", "x1y x2y x3y\n", 0, true)]
    [InlineData("echo $(( 1 + 2 ))\"$(echo a b)\"'c d'", "3a bc d\n", 0, true)]
    [InlineData("echo \"It's\" 'He said \"hi\"' \"a'b\" 'a'\"'\"'b'", "It's He said \"hi\" a'b a'b\n", 0, true)]
    [InlineData("echo a\\ b \"c\\ d\" 'e\\ f'", "a b c\\ d e\\ f\n", 0, true)]
    [InlineData("echo \"$(printf '%s\\n' a b)\"; echo $(printf '%s\\n' a b)", "a\nb\na b\n", 0, true)]
    [InlineData("v=$(printf 'x\\n\\n\\n'); echo \"[$v]\"", "[x]\n", 0, true)]
    [InlineData("echo \"`echo \\`echo nested\\``\"", "nested\n", 0, true)]
    [InlineData("echo $(echo $(echo deep))", "deep\n", 0, true)]
    [InlineData("x='a  b'; echo $x; echo \"$x\"", "a b\na  b\n", 0, true)]
    [InlineData("echo -n \"no newline\"; echo", "no newline\n", 0, true)]
    [InlineData("echo -e 'a\\tb\\nc' ; echo -E 'a\\tb'; echo 'a\\tb'", "a\tb\nc\na\\tb\na\\tb\n", 0, true)]
    [InlineData("echo -e '\\x41\\0101\\e[0m' | od -c | head -1", "0000000   A   A 033   [   0   m  \\n\n", 0, true)]
    [InlineData("echo -- -n; echo -n -e 'x\\n'; echo -ne 'y\\n'; echo -x", "-- -n\nx\ny\n-x\n", 0, true)]
    [InlineData("echo -e 'stop\\chere'; echo after", "stopafter\n", 0, true)]
    [InlineData("printf '%s|' \"a b\" c; echo", "a b|c|\n", 0, true)]
    [InlineData("v='a\"b'; echo \"$v\" \"${v}\" '$v'", "a\"b a\"b $v\n", 0, true)]
    [InlineData("echo \"${PWD##*/}\" >/dev/null; echo ok", "ok\n", 0, true)]
    [InlineData("x=$'line1\\nline2'; echo \"$x\"; echo $x", "line1\nline2\nline1 line2\n", 0, true)]
    [InlineData("echo $((2#101)) \"$((16#ff))\" $((0x1F)) $((010)) $((36#z)) $((64#_))", "5 255 31 8 35 63\n", 0, true)]
    [InlineData("a=\" x \"; [ \"$a\" = \" x \" ] && echo eq", "eq\n", 0, true)]
    [InlineData("echo \"a\"'b'c\"d\"", "abcd\n", 0, true)]
    [InlineData("unset e; echo \"${e}x\" ${e}y", "x y\n", 0, true)]
    [InlineData("IFS=$'\\n'; lines=$(printf 'a b\\nc d'); for l in $lines; do echo \"[$l]\"; done; unset IFS", "[a b]\n[c d]\n", 0, true)]
    [InlineData("v=\"one two\"; arr=(\"$v\" $v); echo ${#arr[@]}", "3\n", 0, true)]
    [InlineData("echo '#not comment' a#b # real comment", "#not comment a#b\n", 0, true)]
    [InlineData("echo a;echo b ; echo c", "a\nb\nc\n", 0, true)]
    [InlineData("x=5 echo $x; x=5; echo $x", "\n5\n", 0, true)]
    [InlineData("echo $((1+1)) $[1+1]", "2 2\n", 0, true)]
    public Task MatchesBash(string script, string stdout, int exitCode, bool quiet) => BashCompat.Check(script, stdout, exitCode, quiet);
}
