using Topwater;

namespace Topwater.Tests;

/// <summary>Redirections and here-documents. Generated from differential runs: each expected value is what bash 5.2.21 printed.</summary>
public class BashCompatRedirections
{
    [Theory]
    [InlineData("echo a > f; echo b >> f; cat f", "a\nb\n", 0, true)]
    [InlineData("ls /nonexistent 2>&1 | head -1 | cut -c1-2", "ls\n", 0, true)]
    [InlineData("{ echo out; echo err >&2; } > o.txt 2>&1; cat o.txt", "out\nerr\n", 0, true)]
    [InlineData("{ echo out; echo err >&2; } &> o.txt; cat o.txt; { echo more; } &>> o.txt; cat o.txt", "out\nerr\nout\nerr\nmore\n", 0, true)]
    [InlineData("{ echo out; echo err >&2; } 2>&1 > o.txt | tr a-z A-Z; cat o.txt", "ERR\nout\n", 0, true)]
    [InlineData("echo x >| f; cat f", "x\n", 0, true)]
    [InlineData("set -o noclobber; echo a > f; echo b > f; echo \"rc=$?\"; echo c >| f; cat f", "rc=1\nc\n", 0, false)]
    [InlineData("cat < /dev/null; echo \"rc=$?\"", "rc=0\n", 0, true)]
    [InlineData("tr a-z A-Z <<< \"hello\"", "HELLO\n", 0, true)]
    [InlineData("cat <<'EOF'\nliteral $HOME `x` \\n\nEOF", "literal $HOME `x` \\n\n", 0, true)]
    [InlineData("cat <<-EOF\n\ttab stripped\n\t\ttwo tabs\n\tEOF", "tab stripped\ntwo tabs\n", 0, true)]
    [InlineData("cat <<EOF | tr a-z A-Z\npiped heredoc\nEOF", "PIPED HEREDOC\n", 0, true)]
    [InlineData("x=$(cat <<EOF\nin subst\nEOF\n); echo \"$x\"", "in subst\n", 0, true)]
    [InlineData("cat <<A; cat <<B\nfirst\nA\nsecond\nB", "first\nsecond\n", 0, true)]
    [InlineData("f() { cat; }; f <<EOF\nto function\nEOF", "to function\n", 0, true)]
    [InlineData("while read -r l; do echo \"> $l\"; done <<EOF\na\nb\nEOF", "> a\n> b\n", 0, true)]
    [InlineData("cat <<EOF\nline \\\ncontinued\nEOF", "line continued\n", 0, true)]
    [InlineData("echo err 1>&2 2>/dev/null; echo ok", "ok\n", 0, false)]
    [InlineData("echo to-stderr >&2 2>/dev/null", "", 0, false)]
    [InlineData("echo hi > /dev/stdout; echo err > /dev/stderr 2>/dev/null; echo x 2>/dev/null >/dev/stderr", "hi\n", 0, false)]
    [InlineData("diff <(echo a) <(echo a) && echo same", "same\n", 0, true)]
    [InlineData("cat < <(echo procsub)", "procsub\n", 0, true)]
    [InlineData("for i in 1 2; do echo $i; done > o.txt; cat o.txt", "1\n2\n", 0, true)]
    [InlineData("if true; then echo in-if; fi > o.txt; cat o.txt", "in-if\n", 0, true)]
    [InlineData("f() { echo from-f; }; f > o.txt; cat o.txt", "from-f\n", 0, true)]
    [InlineData("f() { echo from-f; } > o.txt; f; cat o.txt", "from-f\n", 0, true)]
    [InlineData("echo a > \"file with space\"; cat \"file with space\"", "a\n", 0, true)]
    [InlineData("out=o.txt; echo v > $out; cat $out", "v\n", 0, true)]
    [InlineData("echo x > /nonexistent/dir/f; echo \"rc=$?\"", "rc=1\n", 0, false)]
    [InlineData("cat nofile; echo \"rc=$?\"", "rc=1\n", 0, false)]
    [InlineData("cat < nofile; echo \"rc=$?\"", "rc=1\n", 0, false)]
    [InlineData("echo a >f 2>&1; cat f", "a\n", 0, true)]
    [InlineData("read l < /dev/null; echo \"rc=$? [$l]\"", "rc=1 []\n", 0, true)]
    [InlineData("printf 'x\\ny\\n' > f; while read l; do echo $l; done < f", "x\ny\n", 0, true)]
    [InlineData("exec 3>&1; echo via3 >&3", "via3\n", 0, true)]
    [InlineData("echo foo 3>/dev/null; echo ok", "foo\nok\n", 0, true)]
    [InlineData("{ echo 1; echo 2 >&2; } 2>/dev/null", "1\n", 0, true)]
    [InlineData("ls nonexist 2>/dev/null || echo failed", "failed\n", 0, true)]
    [InlineData("cmd_out=$(echo out; echo err >&2); echo \"[$cmd_out]\"", "[out]\n", 0, false)]
    [InlineData("cmd_out=$( { echo out; echo err >&2; } 2>&1 ); echo \"[$cmd_out]\"", "[out\nerr]\n", 0, true)]
    [InlineData("echo \"a\" | tee f | cat; cat f", "a\na\n", 0, true)]
    [InlineData("cat <<< \"$(echo multi; echo line)\"", "multi\nline\n", 0, true)]
    [InlineData("cat <<\"EOF\"\nquoted delim $x\nEOF", "quoted delim $x\n", 0, true)]
    [InlineData("cat << EOF\nspaced $((1+1))\nEOF", "spaced 2\n", 0, true)]
    public Task MatchesBash(string script, string stdout, int exitCode, bool quiet) => BashCompat.Check(script, stdout, exitCode, quiet);
}
