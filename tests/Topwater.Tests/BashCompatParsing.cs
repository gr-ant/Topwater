using Topwater;

namespace Topwater.Tests;

/// <summary>Parsing corner cases: comments, continuations, keywords as words, syntax errors. Generated from differential runs: each expected value is what bash 5.2.21 printed.</summary>
public class BashCompatParsing
{
    [Theory]
    [InlineData("echo a # comment\n# full comment line\necho b #c", "a\nb\n", 0, true)]
    [InlineData("echo a\\\nb", "ab\n", 0, true)]
    [InlineData("echo if then else fi do done case esac in", "if then else fi do done case esac in\n", 0, true)]
    [InlineData("echo {; echo }", "{\n}\n", 0, true)]
    [InlineData("echo x=1 a=b", "x=1 a=b\n", 0, true)]
    [InlineData("if true; then echo one; fi; if true\nthen\n  echo two\nfi", "one\ntwo\n", 0, true)]
    [InlineData("{ echo a; }; { echo b\n}", "a\nb\n", 0, true)]
    [InlineData("for i in 1 2\ndo\n  echo $i\ndone", "1\n2\n", 0, true)]
    [InlineData("while false; do :; done; until true; do :; done; echo ok", "ok\n", 0, true)]
    [InlineData("f()\n{\n  echo multiline-fn\n}\nf", "multiline-fn\n", 0, true)]
    [InlineData("case x in\n  x)\n    echo matched\n    ;;\n  *)\n    echo no\n    ;;\nesac", "matched\n", 0, true)]
    [InlineData("echo $(case x in x) echo inside;; esac)", "inside\n", 0, true)]
    [InlineData("echo $(echo \"paren ( inside\")", "paren ( inside\n", 0, true)]
    [InlineData("x=$( echo a; echo b ); echo $x", "a b\n", 0, true)]
    [InlineData("echo a#b a #b", "a#b a\n", 0, true)]
    [InlineData("echo ~ ~/ \"~\" '~'", "/home/agent /home/agent/ ~ ~\n", 0, true)]
    [InlineData("true &&\necho continued-and", "continued-and\n", 0, true)]
    [InlineData("false ||\necho continued-or", "continued-or\n", 0, true)]
    [InlineData("echo a |\ntr a b", "b\n", 0, true)]
    [InlineData("if true; then echo a; fi; then", "", 2, false)]
    [InlineData("echo \"unterminated", "", 2, false)]
    [InlineData("fi", "", 2, false)]
    [InlineData("echo $(( 1 + \n2 ))", "3\n", 0, true)]
    [InlineData("[[ a == a ]]\necho $?", "0\n", 0, true)]
    [InlineData("! true; echo $?; ! false; echo $?", "1\n0\n", 0, true)]
    [InlineData("echo \"line1\nline2\"", "line1\nline2\n", 0, true)]
    [InlineData("echo 'multi\nline'", "multi\nline\n", 0, true)]
    [InlineData("a=1 b=2; echo $a $b", "1 2\n", 0, true)]
    [InlineData("x=1 y=$x; echo $y", "1\n", 0, true)]
    [InlineData("echo $((1+1));echo done", "2\ndone\n", 0, true)]
    [InlineData("echo foo;;", "", 2, false)]
    [InlineData("func-name() { echo dashes; }; func-name", "dashes\n", 0, true)]
    [InlineData("f() { echo \"body\"; } ; f", "body\n", 0, true)]
    [InlineData("f(){ echo nospace; }; f", "nospace\n", 0, true)]
    [InlineData(": <<'COMMENT'\nblock comment\nCOMMENT\necho after", "after\n", 0, true)]
    [InlineData("echo \"a\" 'b' $'c'", "a b c\n", 0, true)]
    [InlineData("if [ 1 ]; then :; else :; fi; echo ok", "ok\n", 0, true)]
    [InlineData("( cd /tmp && pwd ); pwd >/dev/null; echo ok", "/tmp\nok\n", 0, true)]
    [InlineData("echo '{\"key\": \"value\"}'", "{\"key\": \"value\"}\n", 0, true)]
    [InlineData("echo \"${x:-{}}\"", "{}\n", 0, true)]
    [InlineData("echo [a] [] ]", "[a] [] ]\n", 0, true)]
    [InlineData("echo a=b=c", "a=b=c\n", 0, true)]
    [InlineData("echo $(echo $(echo a) b) c", "a b c\n", 0, true)]
    [InlineData("echo \"$(echo \"$(echo nested quotes)\")\"", "nested quotes\n", 0, true)]
    [InlineData("v=\"$(echo 'single ) paren')\"; echo \"$v\"", "single ) paren\n", 0, true)]
    [InlineData("x=$(cat <<'EOF'\nhas ) paren\nEOF\n); echo \"$x\"", "has ) paren\n", 0, true)]
    [InlineData("echo \"arr: (1 2)\"", "arr: (1 2)\n", 0, true)]
    [InlineData("echo \\(paren\\)", "(paren)\n", 0, true)]
    [InlineData("[ -n \"x\" ]&&echo tight", "tight\n", 0, true)]
    [InlineData("echo a&&echo b||echo c", "a\nb\n", 0, true)]
    [InlineData("echo $'\\'quoted\\''", "'quoted'\n", 0, true)]
    [InlineData("echo ${#}", "0\n", 0, true)]
    [InlineData("echo \"\\$(not a sub)\"", "$(not a sub)\n", 0, true)]
    [InlineData("echo $'a\\x00b' | od -c | head -1", "0000000   a  \\n\n", 0, true)]
    [InlineData("x=5;y=6;echo $x$y", "56\n", 0, true)]
    [InlineData("declare x=1 y=\"2 3\"; echo \"$x $y\"", "1 2 3\n", 0, true)]
    [InlineData("readonly c=3; echo $c", "3\n", 0, true)]
    [InlineData("export X=1; env | grep -c '^X=1$'", "1\n", 0, true)]
    [InlineData("echo $(( (1 + 2) * 3 ))", "9\n", 0, true)]
    [InlineData("((x = 2 + 3)); echo $x", "5\n", 0, true)]
    [InlineData("echo $((x=7)); echo $x", "7\n7\n", 0, true)]
    [InlineData("echo \"a\nb\" | wc -l", "2\n", 0, true)]
    [InlineData("echo foo > /dev/null && echo yes", "yes\n", 0, true)]
    [InlineData("done", "", 2, false)]
    [InlineData("echo )", "", 2, false)]
    [InlineData("if; then :; fi", "", 2, false)]
    [InlineData("for ; do :; done", "", 2, false)]
    public Task MatchesBash(string script, string stdout, int exitCode, bool quiet) => BashCompat.Check(script, stdout, exitCode, quiet);
}
