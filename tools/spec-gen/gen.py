#!/usr/bin/env python3
"""Generates each port's command tables from spec/ (see spec/README.md).

    python3 tools/spec-gen/gen.py           # write the generated files
    python3 tools/spec-gen/gen.py --check   # exit 1 if they are out of date or the spec is invalid (CI)

Standard library only. The outputs are checked in, so the ports never read spec/ at run time.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "spec"
PORTS = ("cs", "py", "ts")
OUTPUTS = {
    "cs": ROOT / "src/Topwater/Generated/CommandSpec.g.cs",
    "py": ROOT / "python/src/topwater/_spec.py",
    "ts": ROOT / "typescript/src/spec.generated.ts",
}
HEADER = "Generated by tools/spec-gen/gen.py from spec/. Do not edit: change spec/ and rerun the generator."
SLUGS = {".": "dot", ":": "colon", "[": "bracket"}
PLACEHOLDER = re.compile(r"\{([A-Za-z]\w*)(?::([\w-]+))?\}")
QUOTING = {"shell", "shell-always", "locale"}


class SpecError(Exception):
    pass


def validate(value, schema, root, where):
    """The part of JSON Schema the spec's schemas use: $ref, type, enum, required, properties, patternProperties,
    additionalProperties, items, minItems, uniqueItems, minLength, maxLength, pattern and anyOf."""
    if "$ref" in schema:
        node = root
        for part in schema["$ref"].lstrip("#/").split("/"):
            node = node[part]
        return validate(value, node, root, where)
    kinds = {"string": str, "object": dict, "array": list, "boolean": bool}
    t = schema.get("type")
    if t == "integer":
        if not isinstance(value, int) or isinstance(value, bool):
            raise SpecError(f"{where}: must be an integer")
    elif t and not isinstance(value, kinds[t]):
        raise SpecError(f"{where}: must be of type {t}")
    if "enum" in schema and value not in schema["enum"]:
        raise SpecError(f"{where}: must be one of {schema['enum']}")
    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0) or len(value) > schema.get("maxLength", len(value)):
            raise SpecError(f"{where}: {value!r} has the wrong length")
        if "pattern" in schema and not re.search(schema["pattern"], value):
            raise SpecError(f"{where}: {value!r} does not match {schema['pattern']}")
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            raise SpecError(f"{where}: needs at least {schema['minItems']} items")
        if schema.get("uniqueItems") and len({json.dumps(v, sort_keys=True) for v in value}) != len(value):
            raise SpecError(f"{where}: items must be unique")
        for i, v in enumerate(value):
            validate(v, schema.get("items", {}), root, f"{where}[{i}]")
    if isinstance(value, dict):
        for k in schema.get("required", []):
            if k not in value:
                raise SpecError(f"{where}: missing '{k}'")
        props, patterns = schema.get("properties", {}), schema.get("patternProperties", {})
        for k, v in value.items():
            if k in props:
                validate(v, props[k], root, f"{where}.{k}")
                continue
            matched = [s for p, s in patterns.items() if re.search(p, k)]
            for s in matched:
                validate(v, s, root, f"{where}.{k}")
            extra = schema.get("additionalProperties", True)
            if not matched and extra is False:
                raise SpecError(f"{where}: unknown key '{k}'")
            if not matched and isinstance(extra, dict):
                validate(v, extra, root, f"{where}.{k}")
    if "anyOf" in schema:
        errors = []
        for s in schema["anyOf"]:
            try:
                validate(value, s, root, where)
                break
            except SpecError as e:
                errors.append(str(e))
        else:
            raise SpecError(f"{where}: matches none of the allowed forms ({'; '.join(errors)})")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def check_template(where, text):
    for m in PLACEHOLDER.finditer(text):
        if m.group(2) and m.group(2) not in QUOTING:
            raise SpecError(f"{where}: unknown quoting '{m.group(2)}' in {text!r}")


def load():
    command_schema = read_json(SPEC / "command.schema.json")
    shell_schema = read_json(SPEC / "shell.schema.json")
    shell = read_json(SPEC / "shell.json")
    validate(shell, shell_schema, shell_schema, "spec/shell.json")
    commands = []
    for path in sorted((SPEC / "commands").glob("*.json")):
        c = read_json(path)
        where = str(path.relative_to(ROOT))
        validate(c, command_schema, command_schema, where)
        if path.stem != SLUGS.get(c["name"], c["name"]):
            raise SpecError(f"{where}: file name does not match name '{c['name']}'")
        for o in c.get("options", []):
            if not set(o.get("ports", PORTS)) <= set(c.get("ports", PORTS)):
                raise SpecError(f"{where}: option {o}: ports outside the command's")
        for key, text in c.get("messages", {}).items():
            check_template(f"{where}: messages.{key}", text)
        for p in PORTS:
            option_table(c, p)  # raises on clashes
        commands.append(c)
    names = [c["name"] for c in commands]
    if len(names) != len(set(names)):
        raise SpecError("duplicate command names")
    for group in ("getopt", "diagnostics"):
        for key, text in shell[group].items():
            check_template(f"spec/shell.json: {group}.{key}", text)
            if group == "diagnostics" and any(m.group(2) for m in PLACEHOLDER.finditer(text)):
                raise SpecError(f"spec/shell.json: diagnostics.{key}: the shell's messages take plain {{name}} placeholders only")
    return shell, commands


def option_table(c, port):
    """(flags, valued, longs) for Args.Parse in one port: short flag letters, letters that take a value, 'long=key,...'."""
    if c["parser"] != "args":
        return None
    flags, valued, longs, kinds = [], [], [], {}
    for o in c.get("options", []):
        if port not in o.get("ports", PORTS) or o.get("custom"):
            continue  # custom: the command reads it itself, before the shared parser
        key = o.get("key", o.get("short"))
        if kinds.setdefault(key, "arg" in o) != ("arg" in o):
            raise SpecError(f"{c['name']}: option key '{key}' both takes a value and does not ({port})")
        if "short" in o:
            (valued if "arg" in o else flags).append(o["short"])
        elif "arg" in o and key not in valued:
            valued.append(key)  # a long-only option with a value still needs its key in the valued set
        for name in o.get("long", []):
            if any(x.split("=")[0] == name for x in longs):
                raise SpecError(f"{c['name']}: --{name} listed twice ({port})")
            longs.append(f"{name}={key}")
    for letters in (flags, valued):
        if len(letters) != len(set(letters)):
            raise SpecError(f"{c['name']}: a short option is listed twice ({port}): {letters}")
    return "".join(flags), "".join(valued), ",".join(longs)


def fill(template, **values):
    return PLACEHOLDER.sub(lambda m: values.get(m.group(1), m.group(0)), template)


def resolve(shell, c, port):
    """Everything a port needs about one command, with the defaults applied."""
    d = shell["defaults"]
    name = c["name"]
    shown = c.get("reportsAs", name)
    return {
        "name": name,
        "summary": c["summary"],
        "help": "\n".join(c["help"]) + "\n" if "help" in c else None,
        "version": c.get("version", fill(d["version"], name=name)),
        "standardOptions": c.get("standardOptions", True),
        "shellBuiltin": c.get("shellBuiltin", False),
        "programFile": c.get("programFile", True),
        "reportsAs": shown,
        "usageExitCode": c.get("usageExitCode", 1),
        "tryHelp": "\n".join(fill(x, name=shown) for x in c.get("tryHelp", d["tryHelp"])) + "\n",
        "options": option_table(c, port),
        "messages": c.get("messages", {}),
    }


# ---------- emitters ----------

def cs_str(s):
    if s is None:
        return "null"
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def js_str(s):
    return "null" if s is None else json.dumps(s, ensure_ascii=False)


def py_str(s):
    return "None" if s is None else json.dumps(s, ensure_ascii=False)  # JSON string syntax is valid Python


def cs_dict(d, indent):
    if not d:
        return "Empty"
    pad = " " * indent
    return "new Dictionary<string, string>\n" + pad + "{\n" + "".join(f"{pad}    [{cs_str(k)}] = {cs_str(v)},\n" for k, v in d.items()) + pad + "}"


def emit_cs(shell, entries):
    b = lambda v: "true" if v else "false"
    lines = [f"// <auto-generated>{HEADER}</auto-generated>", "#nullable enable", "namespace Topwater;", "",
             "/// <summary>The command tables from spec/: one <see cref=\"Entry\"/> per built-in command this port has.</summary>",
             "internal static partial class CommandSpec", "{",
             "    /// <param name=\"Help\">The --help text when the spec gives one (else the default from the summary).</param>",
             "    /// <param name=\"Options\">Args.Parse's (flags, valued, longs), or null when the command parses its own arguments.</param>",
             "    internal sealed record Entry(string Name, string Summary, string? Help, string Version, bool StandardOptions, bool ShellBuiltin,",
             "        bool ProgramFile, string ReportsAs, int UsageExitCode, string TryHelp, (string Flags, string Valued, string Longs)? Options,",
             "        IReadOnlyDictionary<string, string> Messages);", "",
             "    static readonly IReadOnlyDictionary<string, string> Empty = new Dictionary<string, string>();", "",
             "    internal static readonly IReadOnlyDictionary<string, Entry> Commands = new Dictionary<string, Entry>(StringComparer.Ordinal)",
             "    {"]
    for e in entries:
        o = e["options"]
        opts = f"({cs_str(o[0])}, {cs_str(o[1])}, {cs_str(o[2])})" if o else "null"
        lines.append(f"        [{cs_str(e['name'])}] = new({cs_str(e['name'])}, {cs_str(e['summary'])}, {cs_str(e['help'])}, {cs_str(e['version'])}, "
                     f"{b(e['standardOptions'])}, {b(e['shellBuiltin'])}, {b(e['programFile'])}, {cs_str(e['reportsAs'])}, {e['usageExitCode']}, "
                     f"{cs_str(e['tryHelp'])}, {opts}, {cs_dict(e['messages'], 8)}),")
    lines += ["    };", ""]
    for group, title in (("defaults", None), ("getopt", "Getopt"), ("errno", "Errno"), ("diagnostics", "Diagnostics")):
        if group == "defaults":
            lines.append(f"    internal static readonly IReadOnlyDictionary<string, string> DefaultMessages = {cs_dict(shell['defaults']['messages'], 4)};")
            continue
        lines.append(f"    internal static class {title}")
        lines.append("    {")
        for k, v in shell[group].items():
            lines.append(f"        internal const string {k[0].upper() + k[1:]} = {cs_str(v)};")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_py(shell, entries):
    lines = [f'"""{HEADER}"""', "# fmt: off", "import re as _re", "from typing import NamedTuple, Optional", "", "",
             "class CommandSpec(NamedTuple):",
             '    """One built-in command. help: the --help text when the spec gives one; options: Args.parse\'s (flags, valued, longs) or None."""',
             "    name: str", "    summary: str", "    help: Optional[str]", "    version: str", "    standard_options: bool", "    shell_builtin: bool",
             "    program_file: bool", "    reports_as: str", "    usage_exit_code: int", "    try_help: str", "    options: Optional[tuple]",
             "    messages: dict", "", "", "COMMANDS: dict = {"]
    for e in entries:
        o = e["options"]
        opts = f"({py_str(o[0])}, {py_str(o[1])}, {py_str(o[2])})" if o else "None"
        msgs = "{" + ", ".join(f"{py_str(k)}: {py_str(v)}" for k, v in e["messages"].items()) + "}"
        lines.append(f"    {py_str(e['name'])}: CommandSpec({py_str(e['name'])}, {py_str(e['summary'])}, {py_str(e['help'])}, {py_str(e['version'])}, "
                     f"{e['standardOptions']}, {e['shellBuiltin']}, {e['programFile']}, {py_str(e['reportsAs'])}, {e['usageExitCode']}, "
                     f"{py_str(e['tryHelp'])}, {opts}, {msgs}),")
    lines += ["}", ""]
    lines.append("DEFAULT_MESSAGES = " + json.dumps(shell["defaults"]["messages"], ensure_ascii=False))
    for group in ("getopt", "errno", "diagnostics"):
        lines.append(f"{group.upper()} = {{")
        lines += [f"    {py_str(k)}: {py_str(v)}," for k, v in shell[group].items()]
        lines.append("}")
    lines += ["", "", "def diagnostic(key: str, /, **values: str) -> str:",
              '    """The shell\'s own message `key` with its {placeholders} filled in."""',
              "    return _re.sub(r\"\\{([A-Za-z]\\w*)\\}\", lambda m: values.get(m.group(1), m.group(0)), DIAGNOSTICS[key])"]
    return "\n".join(lines) + "\n"


def emit_ts(shell, entries):
    lines = [f"// {HEADER}", "/* eslint-disable */", "",
             "/** One built-in command. help: the --help text when the spec gives one; options: Args.parse's [flags, valued, longs], or null. */",
             "export interface CommandSpec {", "  readonly name: string;", "  readonly summary: string;", "  readonly help: string | null;",
             "  readonly version: string;", "  readonly standardOptions: boolean;", "  readonly shellBuiltin: boolean;", "  readonly programFile: boolean;",
             "  readonly reportsAs: string;", "  readonly usageExitCode: number;", "  readonly tryHelp: string;",
             "  readonly options: readonly [flags: string, valued: string, longs: string] | null;",
             "  readonly messages: Readonly<Record<string, string>>;", "}", "",
             "export const COMMANDS: ReadonlyMap<string, CommandSpec> = new Map<string, CommandSpec>(["]
    for e in entries:
        o = e["options"]
        opts = f"[{js_str(o[0])}, {js_str(o[1])}, {js_str(o[2])}]" if o else "null"
        msgs = "{ " + ", ".join(f"{js_str(k)}: {js_str(v)}" for k, v in e["messages"].items()) + " }" if e["messages"] else "{}"
        lines.append(f"  [{js_str(e['name'])}, {{ name: {js_str(e['name'])}, summary: {js_str(e['summary'])}, help: {js_str(e['help'])}, "
                     f"version: {js_str(e['version'])}, standardOptions: {js_str(e['standardOptions'])}, shellBuiltin: {js_str(e['shellBuiltin'])}, "
                     f"programFile: {js_str(e['programFile'])}, reportsAs: {js_str(e['reportsAs'])}, usageExitCode: {e['usageExitCode']}, "
                     f"tryHelp: {js_str(e['tryHelp'])}, options: {opts}, messages: {msgs} }}],")
    lines += ["]);", ""]
    lines.append("export const DEFAULT_MESSAGES: Readonly<Record<string, string>> = " + json.dumps(shell["defaults"]["messages"], ensure_ascii=False) + ";")
    for group in ("getopt", "errno", "diagnostics"):
        lines.append(f"export const {group.upper()} = {{")
        lines += [f"  {k}: {js_str(v)}," for k, v in shell[group].items()]
        lines.append("} as const;")
    lines += ["", "/** The shell's own message `key` with its {placeholders} filled in. */",
              "export function diagnostic(key: keyof typeof DIAGNOSTICS, values: Readonly<Record<string, string>> = {}): string {",
              "  return DIAGNOSTICS[key].replace(/\\{([A-Za-z]\\w*)\\}/g, (m, name: string) => values[name] ?? m);",
              "}"]
    return "\n".join(lines) + "\n"


EMITTERS = {"cs": emit_cs, "py": emit_py, "ts": emit_ts}


def generate():
    shell, commands = load()
    out = {}
    for p in PORTS:
        entries = [resolve(shell, c, p) for c in sorted(commands, key=lambda c: c["name"]) if p in c.get("ports", PORTS)]
        out[OUTPUTS[p]] = EMITTERS[p](shell, entries)
    return out


def main(argv):
    check = "--check" in argv
    try:
        outputs = generate()
    except SpecError as e:
        print(f"spec error: {e}", file=sys.stderr)
        return 1
    stale = []
    for path, text in outputs.items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date (run python3 tools/spec-gen/gen.py): " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
